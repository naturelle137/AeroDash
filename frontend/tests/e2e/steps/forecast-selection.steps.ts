import { expect, type Page } from '@playwright/test'
import { createBdd } from 'playwright-bdd'

const { When, Then } = createBdd()

When('the pilot selects a forecast location and time', async ({ page }) => {
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await forecast.getByLabel('Flight phase').selectOption('arrival')
  await forecast.getByLabel('Location').fill('Test airfield')
  await forecast.getByLabel('Local date and time').fill('2030-06-01T12:30')
})
Then('the forecast is unavailable and manual wind remains unchanged', async ({ page }) => {
  await expect(page.getByRole('button', { name: 'Check METAR' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Time-specific forecast' }).getByRole('status')).toContainText('Selection changed; retrieve the forecast again')
  await expect(page.getByLabel('Wind speed', { exact: true })).toHaveValue('20')
})
When('the browser goes offline for forecast planning', async ({ context }) => { await context.setOffline(true) })
Then('the forecast selection and manual wind remain available offline', async ({ page }) => {
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await expect(forecast.getByRole('status')).toContainText('Browser offline')
  await expect(forecast).toContainText('pilot-entered values are not an official forecast')
  await expect(forecast).toContainText('temperature missing or invalid, QNH missing or invalid, wind missing or invalid')
  await expect(forecast.getByLabel('Flight phase')).toHaveValue('arrival')
  await expect(forecast.getByLabel('Location')).toHaveValue('Test airfield')
  await expect(forecast.getByLabel('Local date and time')).toHaveValue('2030-06-01T12:30')
  await expect(page.getByLabel('Wind speed', { exact: true })).toHaveValue('20')
})
Then('the forecast selection evidence is captured as {string}', async ({ page, $testInfo }, width: string) => {
  await page.getByText('Current Flight Prep QNH: 1013 hPa').scrollIntoViewIfNeeded()
  const path = $testInfo.outputPath(`forecast-${width}.png`)
  await page.screenshot({ path })
  await $testInfo.attach(`forecast-${width}`, { path, contentType: 'image/png' })
})

When('the pilot applies synthetic forecast values offline', async ({ page }) => {
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await page.getByRole('radio', { name: 'Derive from QNH and field elevation', exact: true }).check()
  await page.locator('#pa-qnh').fill('995')
  await forecast.getByLabel('Forecast temperature').fill('12')
  await forecast.getByLabel('Forecast QNH').fill('0x3f5')
  await expect(forecast.getByRole('button', { name: 'Apply forecast QNH' })).toBeDisabled()
  await expect(forecast).toContainText('QNH is outside the supported range or is not a valid number')
  await forecast.getByLabel('Forecast QNH').fill('1013')
  await expect(forecast).toContainText('Current Flight Prep QNH: 995 hPa')
  await forecast.getByLabel('QNH source time').fill('2020-12-31T12:00')
  await forecast.getByLabel('QNH time type').selectOption('issue')
  await forecast.getByLabel('Forecast wind direction').fill('180')
  await forecast.getByLabel('Forecast wind speed').fill('10')
  await forecast.getByLabel('Forecast wind unit').selectOption('m/s')
  await expect(forecast).toContainText('temperature entered, QNH entered, wind entered')
  await expect(page.locator('#wind-speed')).toHaveValue('20')
  await forecast.getByRole('button', { name: 'Apply forecast temperature' }).click()
  await forecast.getByRole('button', { name: 'Apply forecast QNH' }).click()
  await expect(forecast).toContainText('Current Flight Prep QNH: 1013 hPa')
  await forecast.getByRole('button', { name: 'Apply forecast wind' }).click()
  await expect(page.locator('#performance-temperature')).toHaveValue('12')
  await expect(page.locator('#wind-speed')).toHaveValue('10')
  await expect(page.locator('#wind-direction')).toHaveValue('180')
  await page.getByRole('radio', { name: 'Derive from QNH and field elevation', exact: true }).check()
  await expect(page.locator('#pa-qnh')).toHaveValue('1013')
  await expect(page.locator('#prep-card-weather')).toContainText('pilot-declared QNH time type: issue')
  await expect(page.locator('#prep-card-weather')).toContainText('Pilot-entered forecast for arrival, Test airfield, 2030-06-01 12:30 local time')
})
Then('a manual override clears forecast provenance', async ({ page }) => {
  await page.locator('#performance-temperature').fill('26')
  await expect(page.locator('#prep-card-weather')).not.toContainText('temperature source: Pilot-entered forecast')
})

When('the pilot retrieves a synthetic hourly forecast', async ({ page }) => {
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await page.route('https://wxdecoder.com/api/airports/kdfw/weather/forecast', route => route.fulfill({ json: { airportIdent: 'KDFW', freshness: { forecastFetchedAt: new Date().toISOString(), stale: false }, hourly: [{ time: '2030-06-01T12:00:00Z', tempF: 68, windDir: 'N', windSpeedKt: 10 }] }, headers: { 'access-control-allow-origin': '*' } }))
  const local = new Date('2030-06-01T12:00:00Z')
  const pad = (n: number) => String(n).padStart(2, '0')
  const time = `${local.getFullYear()}-${pad(local.getMonth() + 1)}-${pad(local.getDate())}T${pad(local.getHours())}:${pad(local.getMinutes())}`
  await forecast.getByLabel('Location').fill('KDFW')
  await forecast.getByLabel('Local date and time').fill(time)
  await forecast.getByRole('button', { name: 'Retrieve US forecast' }).click()
  await expect(forecast).toContainText('Forecast QNH: unavailable')
  await expect(forecast).toContainText('Temperature: 20 °C')
  await expect(page.locator('#wind-speed')).toHaveValue('20')
  await forecast.getByRole('button', { name: 'Replace wind with retrieved forecast' }).click()
  await expect(page.locator('#wind-speed')).toHaveValue('10')
  await expect(page.locator('#prep-card-weather')).toContainText('source fetched')
  await expect(page.locator('#prep-card-weather')).toContainText('source fetch time is not forecast issue time')
})
Then('the retrieved forecast evidence is captured as {string}', async ({ page, $testInfo }, width: string) => {
  const path = $testInfo.outputPath(`retrieved-forecast-${width}.png`)
  await page.locator('#prep-card-weather').scrollIntoViewIfNeeded()
  await page.screenshot({ path })
  await $testInfo.attach(`retrieved-forecast-${width}`, { path, contentType: 'image/png' })
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await forecast.getByLabel('Location').fill('Test airfield')
  await forecast.getByLabel('Local date and time').fill('2030-06-01T12:30')
  await page.locator('#wind-speed').fill('20')
})

When('the pilot retrieves a synthetic global forecast', async ({ page }) => {
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await page.route('https://api.open-meteo.com/v1/forecast?*', route => route.fulfill({ json: { latitude: 50.1, longitude: 8.1, utc_offset_seconds: 0, hourly_units: { time: 'iso8601', temperature_2m: '°C', dew_point_2m: '°C', wind_speed_10m: 'kn', wind_direction_10m: '°', wind_gusts_10m: 'kn', precipitation: 'mm', precipitation_probability: '%', cloud_cover: '%', visibility: 'm', freezing_level_height: 'm' }, hourly: { time: ['2030-06-01T12:00'], temperature_2m: [17], dew_point_2m: [8], wind_speed_10m: [12], wind_direction_10m: [270], wind_gusts_10m: [18], precipitation: [1.2], precipitation_probability: [40], cloud_cover: [75], visibility: [9000], freezing_level_height: [2400] } }, headers: { 'access-control-allow-origin': '*' } }))
  const date = new Date('2030-06-01T12:00:00Z')
  const pad = (n: number) => String(n).padStart(2, '0')
  await forecast.getByLabel('Local date and time').fill(`${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}T${pad(date.getHours())}:${pad(date.getMinutes())}`)
  await forecast.getByLabel('Latitude').fill('50.1')
  await forecast.getByLabel('Longitude').fill('8.6')
  await forecast.getByRole('button', { name: 'Retrieve global model forecast' }).click()
  await expect(forecast).toContainText('Temperature: 17 °C')
  await expect(forecast).toContainText('Model issue time: unavailable')
  await expect(forecast).toContainText('Model total precipitation in the preceding hour: 1.2 mm')
  await expect(forecast).toContainText('Model freezing level: 2400 m above mean sea level')
  await expect(forecast).toContainText('Model dew point at 2 m: 8 °C')
  await expect(page.locator('#wind-speed')).toHaveValue('20')
  await forecast.getByRole('button', { name: 'Replace wind with global forecast' }).click()
  await expect(page.locator('#wind-speed')).toHaveValue('12')
})
Then('the global forecast evidence is captured as {string}', async ({ page, $testInfo }, width: string) => {
  const path = $testInfo.outputPath(`global-forecast-${width}.png`)
  await page.getByText('Model total precipitation in the preceding hour:', { exact: false }).scrollIntoViewIfNeeded()
  await page.screenshot({ path })
  await $testInfo.attach(`global-forecast-${width}`, { path, contentType: 'image/png' })
  await page.locator('#wind-speed').fill('20')
})

const hourLocal = () => {
  const date = new Date('2030-06-01T12:00:00Z')
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}T${pad(date.getHours())}:${pad(date.getMinutes())}`
}
async function retrieveUs(page: Page, body: unknown): Promise<void> {
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await page.unroute('https://wxdecoder.com/api/airports/kdfw/weather/forecast')
  await page.route('https://wxdecoder.com/api/airports/kdfw/weather/forecast', route => route.fulfill({ json: body, headers: { 'access-control-allow-origin': '*' } }))
  await forecast.getByLabel('Location').fill('KDFW')
  await forecast.getByLabel('Local date and time').fill(hourLocal())
  await forecast.getByRole('button', { name: 'Retrieve US forecast' }).click()
}
When('the pilot retrieves a malformed synthetic forecast', async ({ page }) => {
  await retrieveUs(page, { airportIdent: 'KDFW', hourly: 'invalid' })
})
Then('the malformed forecast is rejected and manual wind remains unchanged', async ({ page }) => {
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await expect(forecast.getByRole('status').first()).toContainText('Malformed forecast response.')
  await expect(forecast.getByRole('button', { name: 'Replace wind with retrieved forecast' })).toHaveCount(0)
  await expect(page.locator('#wind-speed')).toHaveValue('20')
})
When('the pilot retrieves an outdated synthetic forecast', async ({ page }) => {
  await retrieveUs(page, { airportIdent: 'KDFW', freshness: { forecastFetchedAt: new Date().toISOString(), stale: true }, hourly: [{ time: '2030-06-01T12:00:00Z', tempF: 68, windDir: 'N', windSpeedKt: 10 }] })
})
Then('the outdated forecast cannot replace manual wind', async ({ page }) => {
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await expect(forecast).toContainText('OUTDATED')
  await expect(forecast.getByRole('button', { name: 'Replace wind with retrieved forecast' })).toBeDisabled()
  await expect(page.locator('#wind-speed')).toHaveValue('20')
})
Then('the outdated forecast evidence is captured as {string}', async ({ page, $testInfo }, width: string) => {
  const path = $testInfo.outputPath(`outdated-forecast-${width}.png`)
  await page.getByRole('region', { name: 'Time-specific forecast' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path })
  await $testInfo.attach(`outdated-forecast-${width}`, { path, contentType: 'image/png' })
})
