import { expect, test } from '@playwright/test'
import { testPohAircraft } from '../fixtures/poh-aircraft'

// Synthetic data exercises software wiring, not aircraft performance.
test('current phase notifications and runway comparisons survive cached offline Flight Prep', async ({ page, context }, info) => {
  await page.goto('/fleet')
  await page.getByTestId('disclaimer-gate-accept').click()
  await page.evaluate(() => navigator.serviceWorker.ready)
  await page.reload()
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  const profile = testPohAircraft()
  profile.registration = 'D-EBPN'; profile.icaoTypeDesignator = 'P208'
  profile.weighingReports[0]!.bem = 600
  profile.certificationCategories[0]!.mtom = 650
  profile.loadPoints = [{ name: 'Synthetic tank', kind: 'fuel', arm: 1, armLookup: [], operationalLimit: 50, defaultQuantity: 40, unit: 'kg', allowableCategories: null, fuelTank: { unusableFuel: 0, permissibleFuelTypes: ['AvGas 100LL'], burnSequences: [] } }]
  for (const table of profile.performanceProfiles!) for (const point of table.dataPoints) point.mass = point.mass === 800 ? 500 : 650
  await page.getByLabel('Or import from Exchange File (.json)').setInputFiles({ name: 'synthetic.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ format: 'aerodash-aircraft', version: 1, profile })) })
  await page.getByRole('button', { name: 'Verify D-EBPN', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Verifier initials').fill('TS')
  await dialog.getByLabel('POH revision').fill('Synthetic wiring only')
  await dialog.getByRole('button', { name: 'Verify', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.goto('/mass-balance')
  const picker = page.getByLabel('Select aircraft', { exact: true })
  await picker.selectOption((await picker.locator('option').filter({ hasText: 'D-EBPN' }).first().getAttribute('value'))!)
  const acknowledgement = page.getByRole('alertdialog', { name: 'Unverified profile acknowledgement' })
  if (await acknowledgement.isVisible()) await acknowledgement.getByRole('button', { name: 'Continue anyway' }).click()
  await page.getByRole('textbox', { name: 'Synthetic tank' }).fill('40')
  await page.getByRole('textbox', { name: 'Synthetic tank' }).blur()
  await context.setOffline(true)
  expect((await page.reload())?.fromServiceWorker()).toBe(true)
  await picker.selectOption((await picker.locator('option').filter({ hasText: 'D-EBPN' }).first().getAttribute('value'))!)
  if (await acknowledgement.isVisible()) await acknowledgement.getByRole('button', { name: 'Continue anyway' }).click()
  await page.getByRole('textbox', { name: 'Synthetic tank' }).fill('40')
  await page.getByRole('textbox', { name: 'Synthetic tank' }).blur()
  const perf = page.getByRole('region', { name: 'Performance', exact: true })
  const runway = perf.getByRole('form', { name: 'Manual runway', exact: true })
  const fuel = page.getByRole('region', { name: 'Fuel & Endurance', exact: true })
  await fuel.getByLabel('Planning method').selectOption('direct')
  await fuel.getByLabel('Trip Fuel (kg)').fill('10')
  await runway.getByLabel('Aerodrome', { exact: true }).fill('TEST')
  await runway.getByLabel('Runway designator', { exact: true }).fill('18')
  await runway.getByLabel('TORA — takeoff run available', { exact: true }).fill('2000')
  await runway.getByLabel('LDA — landing distance available', { exact: true }).fill('2000')
  await runway.getByLabel('Field elevation', { exact: true }).fill('100')
  await runway.getByLabel('Surface type', { exact: true }).selectOption('paved')
  await runway.getByLabel('Surface condition', { exact: true }).selectOption('dry')
  await runway.getByLabel('Source reference').fill('Synthetic AIP reference')
  await runway.getByLabel('Effective date').fill('2026-10-29')
  await runway.getByLabel('Expiry date').fill('2026-11-26')
  await runway.getByRole('button', { name: 'Save runway inputs', exact: true }).click()
  await runway.getByLabel('Check date').fill('2026-11-27')
  await expect(runway).toContainText('Expired according to the declared date')
  await runway.getByLabel('Check date').scrollIntoViewIfNeeded()
  const datePath = info.outputPath('offline-runway-dates.png')
  await page.screenshot({ path: datePath, animations: 'disabled' })
  await info.attach('offline-runway-dates', { path: datePath, contentType: 'image/png' })
  await perf.getByRole('radio', { name: 'Enter pressure altitude directly', exact: true }).check()
  await perf.getByLabel('Pressure altitude (ft)', { exact: true }).fill('1000')
  await perf.getByLabel('Temperature (°C)', { exact: true }).fill('10')
  await perf.getByLabel('Applicable manual configuration').selectOption('s9')
  for (const phase of ['Takeoff', 'Landing']) {
    const inputs = perf.getByRole('group', { name: `${phase} wind and slope` })
    await inputs.getByLabel('Headwind component (kt, negative = tailwind)').fill('0')
    await inputs.getByLabel('Runway slope (%, positive = uphill)').fill('0')
    await expect(perf.getByRole('region', { name: `${phase} corrected distances` }).locator('.comparison')).toContainText('Fits declared runway')
  }
  // Verify each control independently through the live result and its briefing snapshot.
  for (const [phase, slope] of [['Takeoff', '2'], ['Landing', '-2']] as const) {
    const inputs = perf.getByRole('group', { name: `${phase} wind and slope` })
    const result = perf.getByRole('region', { name: `${phase} corrected distances` })
    const finalRoll = result.locator('dd').first()
    const readRoll = async () => Number((await finalRoll.innerText()).match(/^[\d,]+/)![0].replaceAll(',', ''))
    const baseline = await readRoll()
    await inputs.getByLabel('Headwind component (kt, negative = tailwind)').fill('-5')
    await expect.poll(readRoll).toBeGreaterThan(baseline)
    const windy = await readRoll()
    await inputs.getByLabel('Runway slope (%, positive = uphill)').fill(slope)
    await expect.poll(readRoll).toBeGreaterThan(windy)
    const sloped = await readRoll()
    await inputs.getByRole('combobox', { name: 'Safety factor' }).selectOption('custom')
    await inputs.getByLabel('Custom safety factor (1.00–3.00)').fill('2')
    await expect.poll(readRoll).toBeGreaterThan(sloped)
    const final = await readRoll()
    await page.getByRole('button', { name: 'Briefing Pack', exact: true }).click()
    const pack = page.getByRole('dialog', { name: 'Briefing Pack preview' })
    await expect(pack).toContainText(`${final.toLocaleString('en-US')} m`)
    await expect(pack).toContainText('2.00')
    await expect(pack).toContainText('Synthetic AIP reference (user-declared, unverified)')
    const path = info.outputPath(`manual-${phase.toLowerCase()}-${info.project.name}.png`)
    await pack.scrollIntoViewIfNeeded()
    await page.screenshot({ path, animations: 'disabled' })
    await info.attach(`manual-${phase.toLowerCase()}`, { path, contentType: 'image/png' })
    await page.keyboard.press('Escape')
    await inputs.getByRole('combobox', { name: 'Safety factor' }).selectOption('poh-afm')
    await inputs.getByLabel('Headwind component (kt, negative = tailwind)').fill('0')
    await inputs.getByLabel('Runway slope (%, positive = uphill)').fill('0')
  }
  for (const [phase, slope] of [['Takeoff', '-1'], ['Landing', '1']] as const) {
    const inputs = perf.getByRole('group', { name: `${phase} wind and slope` })
    await inputs.getByLabel('Headwind component (kt, negative = tailwind)').fill('5')
    await inputs.getByLabel('Runway slope (%, positive = uphill)').fill(slope)
    const result = perf.getByRole('region', { name: `${phase} corrected distances` })
    await expect(result).toContainText('partially corrected distances')
    await expect(result.locator('.comparison')).toContainText('Comparison uses partially corrected distances')
    await expect(result.locator('.comparison')).toContainText('Do not use this comparison for runway assessment')
    await expect(result).toContainText('Wind component 5 kt was not applied')
    await expect(result).toContainText(`Runway slope ${slope} % was not applied`)
  }
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    const takeoff = perf.getByRole('region', { name: 'Takeoff corrected distances' })
    await takeoff.locator('.comparison').evaluate((element) => element.scrollIntoView({ block: 'center' }))
    const path = info.outputPath(`unapplied-${width}.png`)
    await page.screenshot({ path, animations: 'disabled' })
    await info.attach(`unapplied-${width}`, { path, contentType: 'image/png' })
  }
  await page.getByRole('button', { name: 'Briefing Pack', exact: true }).click()
  const partialPack = page.getByRole('dialog', { name: 'Briefing Pack preview' })
  await expect(partialPack).toContainText('Takeoff partially corrected distances')
  await expect(partialPack).toContainText('Landing partially corrected distances')
  await expect(partialPack).toContainText('Comparison uses partially corrected distances')
  await expect(partialPack).toContainText('Do not use this comparison for runway assessment')
  await expect(partialPack).toContainText('Wind component 5 kt was not applied')
  await expect(partialPack).toContainText('Runway slope -1 % was not applied')
  await expect(partialPack).toContainText('Runway slope 1 % was not applied')
  await page.keyboard.press('Escape')
  await perf.getByLabel('Applicable manual configuration').selectOption('')
  const landingInputs = perf.getByRole('group', { name: 'Landing wind and slope' })
  await landingInputs.getByLabel('Headwind component (kt, negative = tailwind)').fill('0')
  const unsupportedLanding = perf.getByRole('region', { name: 'Landing corrected distances' })
  await expect(unsupportedLanding).toContainText('Wind component 0 kt was not applied')
  await expect(unsupportedLanding).toContainText('The saved runway surface was not applied')
  await expect(unsupportedLanding).toContainText('FSM 3/75 has no landing correction table')
  await expect(unsupportedLanding).toContainText('consult the aircraft manual for these corrections')
  await expect(unsupportedLanding).toContainText('Do not use the uncorrected base distances for runway assessment')
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    await unsupportedLanding.scrollIntoViewIfNeeded()
    const surfacePath = info.outputPath(`unapplied-surface-${width}.png`)
    await page.screenshot({ path: surfacePath, animations: 'disabled' })
    await info.attach(`unapplied-surface-${width}`, { path: surfacePath, contentType: 'image/png' })
  }
  await page.getByRole('button', { name: 'Briefing Pack', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Briefing Pack preview' })).toContainText('The saved runway surface was not applied')
  await expect(page.getByRole('dialog', { name: 'Briefing Pack preview' })).toContainText('Wind component 0 kt was not applied')
  await expect(page.getByRole('dialog', { name: 'Briefing Pack preview' })).toContainText('Do not use the uncorrected base distances for runway assessment')
  await page.keyboard.press('Escape')
  await perf.getByLabel('Applicable manual configuration').selectOption('s9')
  for (const phase of ['Takeoff', 'Landing']) {
    const inputs = perf.getByRole('group', { name: `${phase} wind and slope` })
    await inputs.getByLabel('Headwind component (kt, negative = tailwind)').fill('0')
    await inputs.getByLabel('Runway slope (%, positive = uphill)').fill('0')
  }
  const notes = perf.getByRole('region', { name: 'Performance notifications' })
  await expect(notes).toContainText('WARN-PF-002')
  await expect(notes).not.toContainText('CRIT-PF-002')
  await runway.getByLabel('TORA — takeoff run available', { exact: true }).fill('100')
  await expect(notes).toHaveCount(0)
  await runway.getByLabel('LDA — landing distance available', { exact: true }).fill('100')
  await runway.getByRole('button', { name: 'Save runway inputs', exact: true }).click()
  await expect(notes.locator('[data-notification="CRIT-PF-002"]')).toContainText('Takeoff:')
  await expect(notes.locator('[data-notification="CRIT-PF-002"]')).toContainText('Landing:')
  await notes.scrollIntoViewIfNeeded()
  const path = info.outputPath('offline-flight-prep-notifications.png')
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('offline-flight-prep-notifications', { path, contentType: 'image/png' })
  await page.getByRole('button', { name: 'Briefing Pack', exact: true }).click()
  const pack = page.getByRole('dialog', { name: 'Briefing Pack preview' })
  await expect(pack.getByRole('region', { name: 'Performance notifications' })).toContainText('CRIT-PF-002')
  await page.keyboard.press('Escape')
  await runway.getByLabel('Surface condition', { exact: true }).selectOption('')
  await expect(notes).toHaveCount(0)
  await expect(perf.getByRole('region', { name: 'Takeoff corrected distances' })).toContainText('Not corrected')
  for (const phase of ['Takeoff', 'Landing']) {
    const inputs = perf.getByRole('group', { name: `${phase} wind and slope` })
    await inputs.getByLabel('Headwind component (kt, negative = tailwind)').fill('-5')
    await inputs.getByLabel('Runway slope (%, positive = uphill)').fill('2')
    const result = perf.getByRole('region', { name: `${phase} corrected distances` })
    await expect(result).toContainText('Wind component -5 kt was not applied')
    await expect(result).toContainText('Runway slope 2 % was not applied')
  }
  await page.getByRole('button', { name: 'Briefing Pack', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Briefing Pack preview' })).toContainText('Wind component -5 kt was not applied')
  await expect(page.getByRole('dialog', { name: 'Briefing Pack preview' })).toContainText('Runway slope 2 % was not applied')
})
