import { expect, test } from '@playwright/test'

test('pilot enters forecast QNH offline with its source', async ({ page, context }, info) => {
  await page.goto('/mass-balance')
  const accept = page.getByTestId('disclaimer-gate-accept')
  if (await accept.isVisible()) await accept.click()
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await forecast.getByLabel('Location', { exact: true }).fill('Test airfield')
  await forecast.getByLabel('Local date and time').fill('2099-06-01T12:30')
  await context.setOffline(true)
  await expect(forecast).toContainText('Forecast QNH is unavailable from these services')
  await forecast.getByLabel('QNH unit').selectOption('inHg')
  await forecast.getByLabel('Forecast QNH (inHg)').fill('29.92')
  await expect(forecast).toContainText('QNH to apply: 1013.21 hPa. Applying replaces the current Flight Prep QNH.')
  await expect(forecast).toContainText('QNH selection: departure · Test airfield · 2099-06-01 12:30 device local time')
  await forecast.getByLabel('QNH source (optional)').fill('Pilot briefing')
  await forecast.getByLabel('QNH source time (optional, local)').fill('2020-01-01T10:00')
  await forecast.getByText('QNH to apply:', { exact: false }).scrollIntoViewIfNeeded()
  const path = info.outputPath(`forecast-qnh-${info.project.name}.png`)
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('forecast-qnh', { path, contentType: 'image/png' })
  await forecast.getByRole('button', { name: 'Apply forecast QNH' }).click()
  await expect(page.getByText('pilot-declared QNH source: Pilot briefing', { exact: false })).toBeVisible()
  await expect(page.getByText('pilot-declared QNH source time: 2020-01-01 10:00 local time', { exact: false })).toBeVisible()
  await page.getByText('Derive from QNH and field elevation').click()
  await expect(page.locator('#pa-qnh')).toHaveValue('1013.21')
  await forecast.getByRole('button', { name: 'Clear QNH entry and source' }).click()
  await expect(forecast.getByLabel('Forecast QNH (inHg)')).toHaveValue('')
  await expect(page.locator('#pa-qnh')).toHaveValue('1013.21')
})
