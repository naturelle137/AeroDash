import { expect, test } from '@playwright/test'

test('browser connectivity gates retrieval and preserves manual inputs', async ({ page, context }, info) => {
  await page.goto('/mass-balance')
  const accept = page.getByTestId('disclaimer-gate-accept')
  if (await accept.isVisible()) await accept.click()
  const status = page.getByRole('banner').getByRole('status')
  const buttons = ['Check METAR', 'Check TAF', 'Retrieve US forecast', 'Retrieve DWD ICON forecast', 'Retrieve global model forecast'].map(name => page.getByRole('button', { name, exact: true }))
  await expect(status).toHaveText('Browser online')
  await page.locator('#weather-temperature').fill('15')
  for (const button of buttons) await expect(button).toBeEnabled()
  await context.setOffline(true)
  await expect(status).toHaveText('Browser offline')
  await expect(status).toBeInViewport()
  for (const button of buttons) await expect(button).toBeDisabled()
  await expect(page.locator('#weather-temperature')).toHaveValue('15')
  await page.locator('#weather-temperature').fill('16')
  await page.evaluate(() => window.scrollTo(0, 0))
  const path = info.outputPath(`connectivity-${info.project.name}.png`)
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('offline connectivity', { path, contentType: 'image/png' })
  await context.setOffline(false)
  await expect(status).toHaveText('Browser online')
  for (const button of buttons) await expect(button).toBeEnabled()
  await expect(page.locator('#weather-temperature')).toHaveValue('16')
})
