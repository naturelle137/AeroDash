it('marks a retrieved forecast outdated when its fetch age crosses the limit', async () => {
  vi.useFakeTimers()
  vi.setSystemTime(new Date('2030-01-01T00:00:00Z'))
  vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true)
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, json: async () => ({ airportIdent: 'KDFW', freshness: { forecastFetchedAt: '2029-12-31T20:00:01Z', stale: false }, hourly: [{ time: '2030-01-01T02:00:00Z', tempF: 68, windDir: 'N', windSpeedKt: 10 }] }) }))
  const view = mount(ForecastSelection)
  await view.get('input[type="text"]').setValue('KDFW')
  const local = new Date('2030-01-01T02:00:00Z')
  const pad = (n: number) => String(n).padStart(2, '0')
  await view.get('input[type="datetime-local"]').setValue(`${local.getFullYear()}-${pad(local.getMonth() + 1)}-${pad(local.getDate())}T${pad(local.getHours())}:00`)
  await view.findAll('button').find(button => button.text() === 'Retrieve US forecast')!.trigger('click')
  await vi.advanceTimersByTimeAsync(2000)
  expect(view.text()).toContain('OUTDATED')
  expect(view.findAll('button').find(button => button.text() === 'Replace temperature with retrieved forecast')!.attributes('disabled')).toBeDefined()
  view.unmount()
  vi.unstubAllGlobals()
  vi.useRealTimers()
})
