import { expect, test } from '@playwright/test'

test('fresh METAR suggests a surface and the pilot override survives refresh and offline', async ({ page, context }, info) => {
  await page.route('https://wxdecoder.com/api/wx/EDDF', async (route) => {
    const now = new Date()
    now.setUTCSeconds(0, 0)
    const day = String(now.getUTCDate()).padStart(2, '0')
    const hour = String(now.getUTCHours()).padStart(2, '0')
    const minute = String(now.getUTCMinutes()).padStart(2, '0')
    await route.fulfill({ json: { metar: { raw: `EDDF ${day}${hour}${minute}Z 17004KT 9999 -RA BKN020 10/08 Q1013`, station: 'EDDF', reportTime: now.toISOString(), reportTimeKnown: true } } })
  })
  await page.goto('/mass-balance')
  const accept = page.getByTestId('disclaimer-gate-accept')
  if (await accept.isVisible()) await accept.click()
  const runway = page.getByRole('form', { name: 'Manual runway', exact: true })
  await runway.getByLabel('Aerodrome', { exact: true }).fill('EDDF')
  await runway.getByLabel('Surface type', { exact: true }).selectOption('paved')
  await page.getByLabel('ICAO station code').fill('EDDF')
  await page.getByRole('button', { name: 'Check METAR' }).click()
  const condition = runway.getByLabel('Surface condition', { exact: true })
  await expect(condition).toHaveValue('wet')
  await expect(runway).toContainText('Wet suggested by METAR EDDF')
  await runway.getByText('Wet suggested by METAR', { exact: false }).scrollIntoViewIfNeeded()
  await page.evaluate(() => window.scrollBy(0, 120))
  const path = info.outputPath(`weather-surface-${info.project.name}.png`)
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('weather-surface', { path, contentType: 'image/png' })
  await runway.getByLabel('Runway designator').fill('18')
  await runway.locator('#manual-runway-tora').fill('1000')
  await runway.locator('#manual-runway-tora-unit').selectOption('m')
  await runway.locator('#manual-runway-lda').fill('1000')
  await runway.locator('#manual-runway-lda-unit').selectOption('m')
  await runway.locator('#manual-runway-elevation').fill('0')
  await runway.locator('#manual-runway-elevation-unit').selectOption('m')
  await runway.getByRole('button', { name: 'Save runway inputs' }).click()
  await expect(page.getByRole('region', { name: 'Saved manual runway' })).toContainText('METAR via wxdecoder.com EDDF')
  await page.reload()
  await expect(page.getByRole('region', { name: 'Saved manual runway' })).toContainText('METAR via wxdecoder.com EDDF')
  await page.getByLabel('ICAO station code').fill('EDDF')
  await condition.selectOption('dry')
  await page.getByRole('button', { name: 'Check METAR' }).click()
  await expect(condition).toHaveValue('dry')
  await expect(runway).not.toContainText('Wet suggested by METAR')
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Check METAR' }).click()
  await expect(page.getByText('Offline: METAR retrieval is unavailable.')).toBeVisible()
  await expect(condition).toHaveValue('dry')
})
