import { expect, test } from '@playwright/test'

test('checks an unsaved runway declaration after a cached offline reload', async ({ page, context }, info) => {
  await page.clock.setFixedTime(new Date(2026, 7, 1, 12))
  await page.goto('/mass-balance')
  await page.getByTestId('disclaimer-gate-accept').click()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  const runway = page.getByRole('form', { name: 'Manual runway' })
  await runway.locator('#runway-assessment-date').fill('2026-08-01')
  await runway.locator('#runway-expiry').fill('2026-07-31')
  const check = runway.getByRole('region', { name: 'Runway date check' })
  await expect(check).toContainText('Expired according to the declared date')
  await expect(check).toContainText('Days to declared effect: Unknown')
  await expect(check).toContainText('Days to declared expiry: -1')
  await runway.locator('#runway-effective').fill('2026-08-02')
  await expect(check).toContainText('Expiry must not precede the effective date.')
  await expect(check).not.toContainText('Days to declared expiry:')
  await check.scrollIntoViewIfNeeded()
  const path = info.outputPath(`runway-draft-${info.project.name}.png`)
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('runway-draft', { path, contentType: 'image/png' })
  await runway.locator('#manual-runway-aerodrome').fill('TEST')
  await runway.locator('#manual-runway-designator').fill('27')
  await runway.locator('#manual-runway-tora').fill('1000')
  await runway.locator('#manual-runway-lda').fill('900')
  await runway.locator('#manual-runway-elevation').fill('100')
  await runway.locator('#manual-runway-surface-type').selectOption('paved')
  await runway.locator('#manual-runway-surface-condition').selectOption('dry')
  await runway.locator('#runway-effective').fill('2026-07-01')
  await runway.locator('#runway-expiry').fill('2026-07-31')
  await expect(check).toContainText('Expired according to the declared date')
  await expect(check).toContainText('NOTAM/SUP coverage is unknown')
  await runway.locator('#runway-assessment-date').fill('2026-07-01')
  await expect(check).toContainText('Within the declared dates; source currency remains unverified')
  await expect(check).toContainText('Days to declared effect: 0')
  await expect(check).toContainText('Days to declared expiry: 30')
  await expect(check).toContainText('Unsaved declaration on device date 2026-08-01: Expired')
  await runway.getByRole('button', { name: 'Save runway inputs' }).click()
  await expect(runway.getByRole('region', { name: 'Recently used airports' })).toContainText('Device date 2026-08-01: Expired')
  await runway.locator('#manual-runway-designator').fill('09')
  await expect(check).toContainText('Unsaved declaration on device date 2026-08-01: Expired')
  await check.scrollIntoViewIfNeeded()
  const draftComparison = info.outputPath(`runway-draft-device-date-${info.project.name}.png`)
  await page.screenshot({ path: draftComparison, animations: 'disabled' })
  await info.attach('runway-draft-device-date', { path: draftComparison, contentType: 'image/png' })
  await runway.getByRole('button', { name: 'Discard changes' }).click()
  await expect(check).toContainText('Device date 2026-08-01: Expired according to the declared date')
  await expect(check).toContainText('not source verification')
  await check.scrollIntoViewIfNeeded()
  const comparison = info.outputPath(`runway-device-date-${info.project.name}.png`)
  await page.screenshot({ path: comparison, animations: 'disabled' })
  await info.attach('runway-device-date', { path: comparison, contentType: 'image/png' })
})
