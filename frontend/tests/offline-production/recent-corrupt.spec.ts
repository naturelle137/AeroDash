import { expect, test } from '@playwright/test'

test('preserves unreadable recent declarations when saving offline', async ({ page, context }, info) => {
  await page.goto('/mass-balance')
  await page.getByTestId('disclaimer-gate-accept').click()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await page.evaluate(() => localStorage.setItem('aerodash.performance.recent-airports.v1', '[null]'))
  await context.setOffline(true)
  await page.reload()
  const runway = page.getByRole('form', { name: 'Manual runway' })
  await expect(runway.getByRole('alert')).toContainText('Recent runway declarations could not be read or saved')
  await runway.getByRole('alert').scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('recent-unreadable.png'), animations: 'disabled' })
  await runway.locator('#manual-runway-aerodrome').fill('TEST')
  await runway.locator('#manual-runway-designator').fill('27')
  await runway.locator('#manual-runway-tora').fill('1000')
  await runway.locator('#manual-runway-lda').fill('900')
  await runway.locator('#manual-runway-elevation').fill('100')
  await runway.locator('#manual-runway-surface-type').selectOption('paved')
  await runway.locator('#manual-runway-surface-condition').selectOption('dry')
  await runway.getByRole('button', { name: 'Save runway inputs' }).click()
  await expect(runway).toContainText('Manual runway inputs saved, but recent airports could not be saved.')
  expect(await page.evaluate(() => localStorage.getItem('aerodash.performance.recent-airports.v1'))).toBe('[null]')
  await runway.getByText('Manual runway inputs saved, but recent airports could not be saved.').scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('recent-corrupt.png'), animations: 'disabled' })
})
