import { expect, test } from '@playwright/test'

test('checks dates before restoring a recent declaration offline', async ({ page, context }, info) => {
  await page.goto('/mass-balance')
  await page.getByTestId('disclaimer-gate-accept').click()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  const runway = page.getByRole('form', { name: 'Manual runway' })
  await runway.locator('#manual-runway-aerodrome').fill('TEST')
  await runway.locator('#manual-runway-designator').fill('27')
  await runway.locator('#manual-runway-tora').fill('1000')
  await runway.locator('#manual-runway-lda').fill('900')
  await runway.locator('#manual-runway-elevation').fill('100')
  await runway.locator('#manual-runway-surface-type').selectOption('paved')
  await runway.locator('#manual-runway-surface-condition').selectOption('dry')
  await runway.locator('#runway-effective').fill('2020-01-01')
  await runway.locator('#runway-expiry').fill('2020-12-31')
  await runway.getByRole('button', { name: 'Save runway inputs' }).click()
  await context.setOffline(true)
  await page.reload()
  await runway.locator('#runway-assessment-date').fill('2020-06-01')
  await runway.locator('#manual-runway-designator').fill('09')
  const saveCheck = runway.getByLabel('Date check before saving')
  await expect(saveCheck).toContainText('Selected date 2020-06-01: Within the declared dates')
  await expect(saveCheck).toContainText('Device date')
  await expect(saveCheck).toContainText('Expired according to the declared date')
  await saveCheck.scrollIntoViewIfNeeded()
  const savePath = info.outputPath('save-date-check.png')
  await page.screenshot({ path: savePath, animations: 'disabled' })
  await info.attach('save-date-check', { path: savePath, contentType: 'image/png' })
  await runway.getByRole('region', { name: 'Recently used airports' }).scrollIntoViewIfNeeded()
  const path = info.outputPath('recent-selection.png')
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('recent-selection', { path, contentType: 'image/png' })
  page.once('dialog', async dialog => {
    expect(dialog.message()).toContain('2020-06-01: Within the declared dates')
    expect(dialog.message()).toContain('Device date')
    expect(dialog.message()).toContain('Expired according to the declared date')
    await dialog.dismiss()
  })
  await runway.locator('.select-recent').first().click()
  await expect(runway.locator('#manual-runway-designator')).toHaveValue('09')
})
