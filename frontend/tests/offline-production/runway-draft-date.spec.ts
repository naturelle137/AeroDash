import { expect, test } from '@playwright/test'

test('checks an unsaved runway declaration after a cached offline reload', async ({ page, context }, info) => {
  await page.goto('/mass-balance')
  await page.getByTestId('disclaimer-gate-accept').click()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  const runway = page.getByRole('form', { name: 'Manual runway' })
  await runway.locator('#runway-assessment-date').fill('2026-08-01')
  await runway.locator('#runway-expiry').fill('2026-07-31')
  const check = runway.getByRole('region', { name: 'Runway date check' })
  await expect(check).toContainText('Expired according to the declared date')
  await check.scrollIntoViewIfNeeded()
  const path = info.outputPath(`runway-draft-${info.project.name}.png`)
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('runway-draft', { path, contentType: 'image/png' })
  await runway.locator('#manual-runway-aerodrome').fill('TEST')
  await runway.locator('#manual-runway-designator').fill('27')
  await runway.locator('#manual-runway-tora').fill('1000')
  await runway.locator('#manual-runway-lda').fill('900')
  await runway.locator('#manual-runway-elevation').fill('100')
  await runway.locator('#manual-runway-surface-type').selectOption('paved')
  await runway.locator('#manual-runway-surface-condition').selectOption('dry')
  await runway.locator('#runway-effective').fill('2026-07-01')
  await runway.locator('#runway-expiry').fill('2026-07-31')
  await expect(check).toContainText('Expired according to the declared date')
  await expect(check).toContainText('NOTAM/SUP coverage is unknown')
  await runway.locator('#runway-assessment-date').fill('2026-07-01')
  await expect(check).toContainText('Within the declared dates; source currency remains unverified')
})
