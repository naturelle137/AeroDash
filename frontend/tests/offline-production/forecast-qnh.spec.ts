import { expect, test } from '@playwright/test'

test('pilot enters forecast QNH offline with its source', async ({ page, context }, info) => {
  await page.goto('/mass-balance')
  const accept = page.getByTestId('disclaimer-gate-accept')
  if (await accept.isVisible()) await accept.click()
  const forecast = page.getByRole('region', { name: 'Time-specific forecast' })
  await forecast.getByLabel('Location', { exact: true }).fill('Test airfield')
  await forecast.getByLabel('Local date and time').fill('2099-06-01T12:30')
  await context.setOffline(true)
  await expect(forecast).toContainText('Forecast QNH is unavailable from these services')
  await forecast.getByRole('button', { name: 'Enter aviation QNH manually' }).click()
  await expect(forecast.getByLabel('Forecast QNH (hPa)')).toBeFocused()
  const entryPath = info.outputPath(`forecast-qnh-entry-${info.project.name}.png`)
  await page.screenshot({ path: entryPath, animations: 'disabled' })
  await info.attach('forecast-qnh-entry', { path: entryPath, contentType: 'image/png' })
  await forecast.getByLabel('Forecast QNH (hPa)').fill('1013')
  await expect(forecast).toContainText('QNH source time not recorded; its age is unknown')
  await expect(forecast).toContainText('QNH validity not recorded')
  await forecast.getByLabel('QNH source (optional)').fill('Source A')
  await forecast.getByLabel('QNH source time (optional, local)').fill('2019-01-01T10:00')
  await forecast.getByLabel('QNH valid from (optional, local)').fill('2099-06-01T13:00')
  await forecast.getByLabel('QNH valid until (optional, local)').fill('2099-06-01T14:00')
  await forecast.getByLabel('QNH unit').selectOption('inHg')
  await expect(forecast.getByLabel('Forecast QNH (inHg)')).toHaveValue('')
  await forecast.getByLabel('Forecast QNH (inHg)').fill('29.92')
  await forecast.getByLabel('QNH unit').selectOption('hPa')
  await expect(forecast.getByLabel('Forecast QNH (hPa)')).toHaveValue('1013')
  await expect(forecast.getByLabel('QNH source (optional)')).toHaveValue('Source A')
  await expect(forecast.getByRole('button', { name: 'Apply forecast QNH' })).toBeDisabled()
  await forecast.getByLabel('QNH unit').selectOption('inHg')
  await expect(forecast.getByLabel('Forecast QNH (inHg)')).toHaveValue('29.92')
  await expect(forecast.getByLabel('QNH source (optional)')).toHaveValue('')
  await expect(forecast).toContainText('QNH to apply: 1013.21 hPa. Applying replaces the current Flight Prep QNH.')
  const selectedUtc = await page.evaluate(() => new Date('2099-06-01T12:30').toISOString())
  await expect(forecast).toContainText(`QNH selection: departure · Test airfield · 2099-06-01 12:30 device local time (${selectedUtc})`)
  await forecast.getByText('QNH selection:', { exact: false }).scrollIntoViewIfNeeded()
  const selectionPath = info.outputPath(`forecast-qnh-selection-${info.project.name}.png`)
  await page.screenshot({ path: selectionPath, animations: 'disabled' })
  await info.attach('forecast-qnh-selection', { path: selectionPath, contentType: 'image/png' })
  await forecast.getByLabel('QNH source (optional)').fill('Pilot briefing')
  await forecast.getByLabel('QNH source time (optional, local)').fill('2020-01-01T10:00')
  await forecast.getByLabel('QNH valid from (optional, local)').fill('2099-06-01T12:00')
  await forecast.getByLabel('QNH valid until (optional, local)').fill('2099-06-01T12:30')
  await expect(forecast.getByRole('button', { name: 'Apply forecast QNH' })).toBeDisabled()
  await expect(forecast).toContainText('The selected flight time is at or after the QNH validity end')
  await forecast.getByRole('alert').filter({ hasText: 'QNH validity end' }).scrollIntoViewIfNeeded()
  const validityPath = info.outputPath(`forecast-qnh-validity-${info.project.name}.png`)
  await page.screenshot({ path: validityPath, animations: 'disabled' })
  await info.attach('forecast-qnh-validity', { path: validityPath, contentType: 'image/png' })
  await forecast.getByLabel('QNH valid until (optional, local)').fill('2099-06-01T13:00')
  await expect(forecast).toContainText('days ago; this does not establish freshness')
  const utc = await page.evaluate(() => ['2020-01-01T10:00', '2099-06-01T12:00', '2099-06-01T13:00'].map(value => new Date(value).toISOString()))
  await expect(forecast).toContainText(`QNH source time in UTC: ${utc[0]}`)
  await expect(forecast).toContainText(`QNH validity in UTC: ${utc[1]} to ${utc[2]}`)
  await forecast.getByText('QNH validity in UTC:', { exact: false }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath(`forecast-qnh-utc-${info.project.name}.png`), animations: 'disabled' })
  await forecast.getByRole('button', { name: 'Apply forecast QNH' }).click()
  await expect(page.getByText('pilot-entered QNH: 29.92 inHg', { exact: false })).toBeVisible()
  await page.getByText('pilot-entered QNH: 29.92 inHg', { exact: false }).scrollIntoViewIfNeeded()
  const path = info.outputPath(`forecast-qnh-${info.project.name}.png`)
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('forecast-qnh', { path, contentType: 'image/png' })
  await expect(page.getByText('pilot-declared QNH source: Pilot briefing', { exact: false })).toBeVisible()
  await expect(page.getByText('pilot-declared QNH source time: 2020-01-01 10:00 local time', { exact: false })).toBeVisible()
  await expect(page.getByText('pilot-declared QNH validity: 2099-06-01 12:00 to 2099-06-01 13:00 local time', { exact: false })).toBeVisible()
  await page.getByText('Derive from QNH and field elevation').click()
  await expect(page.locator('#pa-qnh')).toHaveValue('1013.21')
  await expect(forecast).toContainText('QNH drafts: hPa present · inHg present')
  await forecast.getByRole('button', { name: 'Clear current inHg QNH draft' }).click()
  await expect(page.getByText('pilot-entered QNH: 29.92 inHg', { exact: false })).toBeVisible()
  await expect(forecast).toContainText('QNH drafts: hPa present · inHg empty')
  await forecast.getByLabel('QNH unit').selectOption('hPa')
  await expect(forecast.getByLabel('Forecast QNH (hPa)')).toHaveValue('1013')
  await forecast.getByRole('button', { name: 'Clear QNH entry and source' }).click()
  await forecast.getByLabel('QNH unit').selectOption('inHg')
  await expect(forecast.getByLabel('Forecast QNH (inHg)')).toHaveValue('')
  await expect(page.locator('#pa-qnh')).toHaveValue('1013.21')
  await forecast.getByLabel('QNH unit').selectOption('hPa')
  await expect(forecast.getByLabel('Forecast QNH (hPa)')).toHaveValue('')
})

