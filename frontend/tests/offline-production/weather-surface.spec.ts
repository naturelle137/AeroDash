import { expect, test } from '@playwright/test'

test('fresh METAR suggests a surface and the pilot override survives refresh and offline', async ({ page, context }, info) => {
  await page.route('https://wxdecoder.com/api/wx/EDDF', async (route) => {
    const now = new Date()
    now.setUTCSeconds(0, 0)
    const day = String(now.getUTCDate()).padStart(2, '0')
    const hour = String(now.getUTCHours()).padStart(2, '0')
    const minute = String(now.getUTCMinutes()).padStart(2, '0')
    await route.fulfill({ json: { metar: { raw: `EDDF ${day}${hour}${minute}Z 17004KT 9999 -RA BKN020 10/08 Q1013 TEMPO 4000 BR`, station: 'EDDF', reportTime: now.toISOString(), reportTimeKnown: true } } })
  })
  await page.goto('/mass-balance')
  const accept = page.getByTestId('disclaimer-gate-accept')
  if (await accept.isVisible()) await accept.click()
  const runway = page.getByRole('form', { name: 'Manual runway', exact: true })
  await runway.getByLabel('Aerodrome', { exact: true }).fill('EDDF')
  await runway.getByLabel('Surface type', { exact: true }).selectOption('paved')
  await page.locator('#weather-icao').fill('EDDF')
  await page.getByRole('button', { name: 'Check METAR' }).click()
  const condition = runway.getByLabel('Surface condition', { exact: true })
  await expect(condition).toHaveValue('wet')
  await expect(runway).toContainText('Wet suggested by METAR EDDF')
  await runway.getByText('Wet suggested by METAR', { exact: false }).scrollIntoViewIfNeeded()
  await page.evaluate(() => window.scrollBy(0, 120))
  const path = info.outputPath(`weather-surface-${info.project.name}.png`)
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('weather-surface', { path, contentType: 'image/png' })
  await runway.getByLabel('Runway designator').fill('18')
  await runway.locator('#manual-runway-tora').fill('1000')
  await runway.locator('#manual-runway-tora-unit').selectOption('m')
  await runway.locator('#manual-runway-lda').fill('1000')
  await runway.locator('#manual-runway-lda-unit').selectOption('m')
  await runway.locator('#manual-runway-elevation').fill('0')
  await runway.locator('#manual-runway-elevation-unit').selectOption('m')
  await runway.getByRole('button', { name: 'Save runway inputs' }).click()
  await expect(page.getByRole('region', { name: 'Saved manual runway' })).toContainText('METAR via wxdecoder.com EDDF')
  await page.reload()
  await expect(page.getByRole('region', { name: 'Saved manual runway' })).toContainText('METAR via wxdecoder.com EDDF')
  await page.locator('#weather-icao').fill('EDDF')
  await condition.selectOption('dry')
  await page.getByRole('button', { name: 'Check METAR' }).click()
  await expect(condition).toHaveValue('dry')
  await expect(runway).not.toContainText('Wet suggested by METAR')
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Check METAR' }).click()
  await expect(page.getByText('Offline: METAR retrieval is unavailable.')).toBeVisible()
  await expect(condition).toHaveValue('dry')
})

test('TAF applicability, unsupported groups, saved provenance and pilot override', async ({ page, context }, info) => {
  await page.clock.install({ time: new Date('2026-11-21T13:58:00Z') })
  const base = 'TAF EDDF 211100Z 2112/2118 21005KT 9999'
  let raw = `${base} BKN020 TEMPO 2114/2116 4000 RA BKN010`
  await page.route('https://wxdecoder.com/api/wx/EDDF', route => route.fulfill({ json: {
    taf: { raw, station: 'EDDF', issueTime: '2026-11-21T11:00:00.000Z', validFrom: '2026-11-21T12:00:00.000Z', validTo: '2026-11-21T18:00:00.000Z' },
  } }))
  await page.goto('/mass-balance')
  const accept = page.getByTestId('disclaimer-gate-accept')
  if (await accept.isVisible()) await accept.click()
  const runway = page.getByRole('form', { name: 'Manual runway', exact: true })
  const condition = runway.getByLabel('Surface condition', { exact: true })
  await runway.getByLabel('Aerodrome', { exact: true }).fill('EDDF')
  await runway.getByLabel('Surface type', { exact: true }).selectOption('paved')
  await page.locator('#taf-icao').fill('EDDF')
  const check = page.getByRole('button', { name: 'Check TAF', exact: true })
  await page.clock.pauseAt(new Date('2026-11-21T13:59:59Z'))
  await check.click()
  await expect(page.getByText(raw, { exact: true })).toBeVisible()
  await expect(condition).toHaveValue('')
  await page.clock.fastForward(1000)
  await expect(condition).toHaveValue('wet')
  await expect(runway).toContainText('Wet suggested by TAF EDDF')
  await page.clock.fastForward(2 * 60 * 60 * 1000)
  await expect(condition).toHaveValue('')
  raw = `${base} RA BKN020 UNKNOWN RA`
  await check.click()
  await expect(page.getByText('No applicable surface suggestion:', { exact: false })).toBeVisible()
  await expect(condition).toHaveValue('')
  raw = `${base} -DZ BKN020`
  await check.click()
  await expect(condition).toHaveValue('wet')
  await context.setOffline(true)
  await expect(condition).toHaveValue('')
  await expect(page.getByText('Offline: TAF retrieval is unavailable.')).toBeVisible()
  await context.setOffline(false)
  await check.click()
  await expect(condition).toHaveValue('wet')
  await page.clock.fastForward(2 * 60 * 60 * 1000)
  await expect(page.getByText('EXPIRED forecast', { exact: false })).toBeVisible()
  await expect(condition).toHaveValue('')
  await page.clock.setSystemTime(new Date('2026-11-21T16:00:00Z'))
  await check.click()
  await expect(condition).toHaveValue('wet')
  await runway.getByText('Wet suggested by TAF', { exact: false }).scrollIntoViewIfNeeded()
  const path = info.outputPath(`taf-surface-${info.project.name}.png`)
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach('TAF runway provenance', { path, contentType: 'image/png' })
  await runway.getByLabel('Runway designator').fill('18')
  await runway.locator('#manual-runway-tora').fill('1000')
  await runway.locator('#manual-runway-tora-unit').selectOption('m')
  await runway.locator('#manual-runway-lda').fill('1000')
  await runway.locator('#manual-runway-lda-unit').selectOption('m')
  await runway.locator('#manual-runway-elevation').fill('0')
  await runway.locator('#manual-runway-elevation-unit').selectOption('m')
  await runway.getByRole('button', { name: 'Save runway inputs' }).click()
  await page.reload()
  const saved = page.getByRole('region', { name: 'Saved manual runway' })
  await expect(saved).toContainText('TAF via wxdecoder.com EDDF')
  await expect(saved).toContainText('valid 2026-11-21T12:00:00.000Z to 2026-11-21T18:00:00.000Z')
  await condition.selectOption('dry')
  await page.locator('#taf-icao').fill('EDDF')
  await check.click()
  await expect(condition).toHaveValue('dry')
  await context.setOffline(true)
  await expect(condition).toHaveValue('dry')
})
