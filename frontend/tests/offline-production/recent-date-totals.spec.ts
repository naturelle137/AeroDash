import { expect, test } from '@playwright/test'

test('summarizes recent declared date checks offline', async ({ page, context }, info) => {
  await page.goto('/mass-balance')
  await page.getByTestId('disclaimer-gate-accept').click()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  const runway = page.getByRole('form', { name: 'Manual runway' })
  await runway.locator('#runway-assessment-date').fill('2026-08-01')
  await runway.locator('#manual-runway-aerodrome').fill('TEST')
  await runway.locator('#manual-runway-designator').fill('27')
  await runway.locator('#manual-runway-tora').fill('1000')
  await runway.locator('#manual-runway-lda').fill('900')
  await runway.locator('#manual-runway-elevation').fill('100')
  await runway.locator('#manual-runway-surface-type').selectOption('paved')
  await runway.locator('#manual-runway-surface-condition').selectOption('dry')
  await runway.locator('#runway-expiry').fill('2026-07-31')
  await runway.getByRole('button', { name: 'Save runway inputs' }).click()
  await runway.locator('#manual-runway-designator').fill('09')
  await runway.locator('#runway-expiry').fill('')
  await runway.getByRole('button', { name: 'Save runway inputs' }).click()
  const recent = runway.getByRole('region', { name: 'Recently used airports' })
  const totals = recent.getByLabel('Recent declaration date check totals')
  await expect(totals).toContainText('Expired: 1')
  await expect(totals).toContainText('Unknown: 1')
  await recent.locator('#recent-status').selectOption('expired')
  await expect(totals).toContainText('All recent declarations: 2')
  await expect(recent.locator('li')).toHaveCount(1)
  await recent.scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('recent-date-totals.png'), animations: 'disabled' })
  await runway.locator('#runway-assessment-date').fill('2026-07-31')
  await expect(totals).toContainText('Expired: 0')
  await expect(totals).toContainText('Unknown: 2')
})
