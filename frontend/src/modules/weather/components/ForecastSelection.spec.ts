import { mount } from '@vue/test-utils'
import { afterEach, expect, it, vi } from 'vitest'
import ForecastSelection from './ForecastSelection.vue'

afterEach(() => vi.restoreAllMocks())

it('keeps a synthetic selection when browser connectivity changes', async () => {
  vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true)
  const view = mount(ForecastSelection)
  await view.get('select').setValue('arrival')
  await view.get('input[type="text"]').setValue('Test airfield')
  await view.get('input[type="datetime-local"]').setValue('2030-06-01T12:30')
  expect(view.get('[role="status"]').text()).toContain('No forecast source is configured')
  vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(false)
  window.dispatchEvent(new Event('offline'))
  await view.vm.$nextTick()
  expect(view.get('[role="status"]').text()).toContain('Browser offline')
  expect((view.get('select').element as HTMLSelectElement).value).toBe('arrival')
  expect((view.get('input[type="text"]').element as HTMLInputElement).value).toBe('Test airfield')
  expect((view.get('input[type="datetime-local"]').element as HTMLInputElement).value).toBe('2030-06-01T12:30')
  view.unmount()
})

it('applies only valid pilot entries associated with a future selection', async () => {
  vi.useFakeTimers()
  vi.setSystemTime(new Date('2030-01-01T00:00:00'))
  const view = mount(ForecastSelection)
  const field = (label: string) => view.findAll('label').find(item => item.text().includes(label))!.get('input')
  const button = (text: string) => view.findAll('button').find(item => item.text() === text)!
  await field('Forecast temperature').setValue('12')
  await button('Apply forecast temperature').trigger('click')
  expect(view.emitted('apply')).toBeUndefined()
  await field('Location').setValue('Test airfield')
  await field('Local date').setValue('2030-06-01T12:30')
  await field('Forecast temperature').setValue('12')
  await field('Forecast QNH').setValue('1200')
  expect(button('Apply forecast QNH').attributes('disabled')).toBeDefined()
  await field('Forecast QNH').setValue('1013')
  await field('Forecast wind speed').setValue('10')
  expect(button('Apply forecast wind').attributes('disabled')).toBeDefined()
  await field('Forecast wind direction').setValue('180')
  await view.findAll('select')[1]!.setValue('m/s')
  await button('Apply forecast wind').trigger('click')
  expect(view.emitted('apply')![0]).toEqual(['wind', { temperature: '12', qnh: '1013', wind: { direction: '180', speed: '10', unit: 'm/s' } }, 'Pilot-entered forecast for departure, Test airfield, 2030-06-01 12:30 local time'])
  await field('Location').setValue('Another airfield')
  expect((field('Forecast temperature').element as HTMLInputElement).value).toBe('')
  await field('Forecast temperature').setValue('12')
  vi.setSystemTime(new Date('2030-07-01T00:00:00'))
  await button('Apply forecast temperature').trigger('click')
  expect(view.emitted('apply')).toHaveLength(1)
  view.unmount()
  vi.useRealTimers()
})
